function frontMatter(article) {
  const tags = JSON.stringify(article.tags);
  const heroQ = encodeURIComponent(article.title);
  let fm = `---
layout: article.njk
title: ${article.title}
description: ${article.description}
date: ${article.date}
category: ${article.category}
tags: ${tags}
heroImage: "https://tse-mm.bing.com/th?q=${heroQ}"
heroAlt: "${article.title} 配图"
`;
  if (article.video) {
    fm += `videoTitle: "${article.title}"
videoDescription: "本教程配合图文步骤，展示 ${article.title} 的完整流程。"
videoPoster: "https://tse-mm.bing.com/th?q=${heroQ}%20video%20tutorial"
`;
  }
  fm += `---\n\n${article.body}\n`;
  return fm;
}

async function main() {
  await fs.mkdir(blogDir, { recursive: true });
  for (const article of articles) {
    await fs.writeFile(path.join(blogDir, `${article.slug}.md`), frontMatter(article), "utf8");
  }
  console.log(`Seeded ${articles.length} articles.`);
}

main();
